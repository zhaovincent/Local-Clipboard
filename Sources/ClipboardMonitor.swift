import AppKit

/// 轮询系统剪贴板，捕获文本 / 图片 / 文件，并过滤密码管理器等私密内容
final class ClipboardMonitor {
    private let store: HistoryStore
    private var timer: Timer?
    private var lastChange: Int = -1
    private let maxTextLength = 500_000

    /// 自己写回剪贴板时记录 changeCount，避免把「复制历史」再记一遍
    static var selfWriteCount: Int = -1

    init(store: HistoryStore) {
        self.store = store
    }

    func start() {
        lastChange = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            self?.tick()
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func tick() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        if count == lastChange { return }
        lastChange = count
        if count == ClipboardMonitor.selfWriteCount { return }
        capture(pb)
    }

    /// 多类型兜底读取文本：某些写入方（如 pbcopy）只声明旧式类型，
    /// `string(forType: .string)` 会返回空串，必须逐个类型尝试。
    private func readString(_ pb: NSPasteboard) -> String? {
        if let s = pb.string(forType: .string), !s.isEmpty { return s }

        let extraTypes = [
            NSPasteboard.PasteboardType("public.utf8-plain-text"),
            NSPasteboard.PasteboardType("NSStringPboardType"),
            NSPasteboard.PasteboardType("public.utf16-plain-text"),
            NSPasteboard.PasteboardType("public.utf16-external-plain-text"),
            NSPasteboard.PasteboardType("com.apple.traditional-mac-plain-text")
        ]
        for t in extraTypes {
            if let s = pb.string(forType: t), !s.isEmpty { return s }
        }

        if let arr = pb.readObjects(forClasses: [NSString.self], options: nil),
           let s = arr.first as? String, !s.isEmpty {
            return s
        }

        if let rtf = pb.data(forType: .rtf),
           let attr = NSAttributedString(rtf: rtf, documentAttributes: nil),
           !attr.string.isEmpty {
            return attr.string
        }

        // 最后兜底：任意类型只要能按 UTF-8 解出可打印文本
        for t in pb.types ?? [] {
            if let d = pb.data(forType: t), d.count > 0, d.count < 2_000_000,
               let str = String(data: d, encoding: .utf8),
               !str.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
               !str.contains("\u{0}") {
                return str
            }
        }
        return nil
    }

    private func capture(_ pb: NSPasteboard) {
        let types = pb.types ?? []
        if types.isEmpty { return }

        // 过滤密码 / 临时 / 自动生成内容
        let ignoredMarkers = [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
            "com.agilebits.onepassword"
        ]
        for t in types where ignoredMarkers.contains(where: { t.rawValue.localizedCaseInsensitiveContains($0) }) {
            return
        }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        // 1. 文件
        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map { $0.path }.joined(separator: "\n")
            store.add(ClipItem(kind: .file, text: paths, source: source, byteSize: paths.utf8.count))
            return
        }

        // 2. 图片
        if types.contains(.png) || types.contains(.tiff) {
            var cg: CGImage?
            if let data = pb.data(forType: .png), let provider = CGDataProvider(data: data as CFData) {
                cg = CGImage(pngDataProviderSource: provider, decode: nil, shouldInterpolate: true, intent: .defaultIntent)
            }
            if cg == nil, let img = pb.readObjects(forClasses: [NSImage.self], options: nil)?.first as? NSImage {
                cg = img.cgImage(forProposedRect: nil, context: nil, hints: nil)
            }
            if let cg, let saved = store.storeImage(cg) {
                let item = ClipItem(kind: .image,
                                    text: L10n.imageItem(saved.1, saved.2),
                                    imageBase: saved.0,
                                    width: saved.1,
                                    height: saved.2,
                                    source: source,
                                    byteSize: saved.3)
                store.add(item)
                return
            }
        }

        // 3. 文本 / 链接
        let text = readString(pb)
        guard var s = text, !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        if s.count > maxTextLength { s = String(s.prefix(maxTextLength)) }
        let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
        let isLink = (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"))
            && !trimmed.contains(" ")
            && trimmed.count < 2048
        store.add(ClipItem(kind: isLink ? .link : .text,
                           text: s,
                           source: source,
                           byteSize: s.utf8.count))
    }
}
